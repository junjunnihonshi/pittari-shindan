掃除機をかけても髪の毛が残る。以前は簡単に吸い取れていたゴミを、何度も往復しないと取れなくなった。そんなとき、最初に確認したいのはゴミが通る経路です。

掃除機は、ダストケースや紙パックだけでなく、フィルター、ヘッド、ホースにゴミがたまることでも吸引力が落ちます。コードレス式ではバッテリー残量や運転モードも関係します。

