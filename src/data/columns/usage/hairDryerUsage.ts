髪に水分が大量に残っていると、ドライヤーを当てる時間が長くなります。

あらかじめタオルで水分を取れば、温風を当てる時間を短くしやすくなります。

髪が絡まっている場合は、無理に引っ張らず、手ぐしや髪質に合うブラシでやさしく整えてください。

