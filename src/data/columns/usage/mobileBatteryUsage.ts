モバイルバッテリー本体を充電するための入力と、スマートフォンなどに電力を供給するための出力は別の機能です。

USB-C端子が入力・出力の両方に対応する製品もあります。

ただし、すべての端子で同じ機能が使えるとは限りません。

IN、OUTなどの表示やメーカー仕様を確認してください。

