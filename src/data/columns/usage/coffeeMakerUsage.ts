毎朝使うコーヒーメーカー。サーバーやフィルターは洗っていても、水タンクやミル、内部の給湯経路まで手入れできているでしょうか。

コーヒーメーカーには、ドリップ式、ミル付き全自動、カプセル式などがあり、洗う部品や清掃方法が異なります。

水に含まれるミネラル分が内部に蓄積すると、お湯の出が悪くなる場合があります。また、コーヒー粉や豆の油分が残ると、ニオイや味に影響することもあります。

