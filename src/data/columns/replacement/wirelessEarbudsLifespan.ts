メーカーによっては修理ではなく交換サービスとなる場合もあります。

確認したい項目は次のとおりです。

- 保証期間内かどうか
- 片側だけの交換が可能か
- バッテリーサービスの費用
- 充電ケースの交換費用
- 新品の購入価格

