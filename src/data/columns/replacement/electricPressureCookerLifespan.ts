処分する際は、調理を終了し、圧力が完全に抜け、本体が十分冷めていることを確認しましょう。

内鍋の食材や水を取り除き、自治体や販売店の案内に従ってください。

本体の電気部品や圧力機構を自分で分解する必要はありません。

